/**
 * Raw post content (as an export file carries it) → the HTML WordPress would
 * have shown.
 *
 * The REST API hands over content after WordPress's display filters; an
 * export file hands over what is in the database. Two of those filters change
 * what the content *means*, so they are reproduced here: blocks are unwrapped
 * from their `<!-- wp:… -->` comments (dynamic blocks noted, reusable blocks
 * inlined), and classic-editor text gets `wpautop`'s paragraphs — without it,
 * a classic post's blank lines would vanish and every paragraph would run
 * together.
 */

export interface RawResult {
  html: string;
  /** Text before `<!--more-->`, when the post had one (the classic teaser). */
  teaser?: string;
  /** Blocks generated by the site at view time (latest posts, a query loop), which carry no content of their own. */
  dynamicBlocks: string[];
  /** Reusable blocks referred to but not present in the export. */
  missingReusable: number[];
  hasBlocks: boolean;
}

/**
 * A block delimiter is an HTML comment: `<!-- wp:name {"json":1} -->`,
 * `<!-- /wp:name -->`, or the self-closing `<!-- wp:name {…} /-->`. WordPress
 * escapes "--" inside the JSON, so a delimiter always ends at the first "-->".
 */
const COMMENT = /<!--([\s\S]*?)-->/g;
const DELIMITER = /^\s+(\/)?wp:([a-z][a-z0-9_-]*(?:\/[a-z][a-z0-9_-]*)?)(?:\s+(\{[\s\S]*\}))?\s+(\/)?$/;

function attrsOf(json: string | undefined): Record<string, unknown> {
  if (!json) return {};
  try {
    return JSON.parse(json) as Record<string, unknown>;
  } catch {
    return {};
  }
}

export function prepareRaw(content: string, reusable: Record<number, string>, depth = 0): RawResult {
  const hasBlocks = content.includes("<!-- wp:");
  const dynamicBlocks: string[] = [];
  const missingReusable: number[] = [];
  let html = content.replace(/\r\n?/g, "\n");

  if (hasBlocks) {
    html = html.replace(COMMENT, (match, inner: string) => {
      const delimiter = DELIMITER.exec(inner);

      if (!delimiter) return match;
      const [, closer, fullName = "", json, selfClosing] = delimiter;
      const name = fullName.replace(/^core\//, "");

      if (closer || !selfClosing) return "";
      if (name === "block") {
        const ref = Number(attrsOf(json).ref);
        const inner = reusable[ref];

        if (inner !== undefined && depth < 3) {
          const nested = prepareRaw(inner, reusable, depth + 1);

          dynamicBlocks.push(...nested.dynamicBlocks);
          missingReusable.push(...nested.missingReusable);
          return nested.html;
        }
        missingReusable.push(ref);
        return `<!-- gwp:missing-reusable ${ref} -->`;
      }
      // Self-closing blocks carry no saved markup: the site generates them when the page is shown.
      if (!/^(spacer|separator|more|nextpage)$/.test(name)) {
        dynamicBlocks.push(name);
        return `<!-- gwp:dynamic ${name} -->`;
      }
      return "";
    });
  }

  let teaser: string | undefined;
  const more = /<!--more(.*?)?-->/.exec(html);

  if (more) {
    teaser = html.slice(0, more.index).trim();
    html = `${html.slice(0, more.index)}${html.slice(more.index + more[0].length)}`;
  }
  // A paginated post (<!--nextpage-->) becomes one page; a rule marks where the breaks were.
  html = html.replace(/<!--nextpage-->/g, "\n<hr>\n");
  if (!hasBlocks) html = wpautop(html);
  return { html, dynamicBlocks, missingReusable, hasBlocks, ...(teaser ? { teaser: hasBlocks ? teaser : wpautop(teaser) } : {}) };
}

const ALL_BLOCKS =
  "(?:table|thead|tfoot|caption|col|colgroup|tbody|tr|td|th|div|dl|dd|dt|ul|ol|li|pre|form|map|area|blockquote|address|math|style|p|h[1-6]|hr|fieldset|legend|section|article|aside|hgroup|header|footer|nav|figure|figcaption|details|menu|summary)";

/**
 * A port of WordPress's wpautop(): blank lines become paragraphs, single
 * newlines become line breaks, block elements are left alone. It works on
 * text with HTML in it, as the original does — this is reproducing what
 * WordPress shows, not parsing HTML, so it follows the original step for
 * step rather than "improving" on it.
 */
export function wpautop(input: string, br = true): string {
  if (input.trim() === "") return "";
  let text = `${input}\n`;
  const preserved: string[] = [];
  const keep = (value: string) => {
    preserved.push(value);
    // Like WordPress's own placeholder, it is a <pre> so the block rules treat it as one.
    return `<pre data-gwp-keep="${preserved.length - 1}"></pre>`;
  };

  // <pre>, <script> and <style> keep their newlines exactly.
  text = text.replace(/<(pre|script|style|svg|textarea)[\s>][\s\S]*?<\/\1>/gi, (match) => keep(match));
  text = text.replace(/<br\s*\/?>\s*<br\s*\/?>/gi, "\n\n");
  text = text.replace(new RegExp(`(<${ALL_BLOCKS}[\\s/>])`, "gi"), "\n\n$1");
  text = text.replace(new RegExp(`(</${ALL_BLOCKS}>)`, "gi"), "$1\n\n");
  text = text.replace(/<hr\s*?\/?>/gi, "<hr />\n\n");
  text = text.replace(/\r\n|\r/g, "\n");
  // Newlines inside a tag's attributes are not paragraph breaks.
  text = text.replace(/<[^<>]+>/g, (tag) => tag.replace(/\n/g, " "));
  text = text.replace(/\s*<option/g, "<option").replace(/<\/option>\s*/g, "</option>");
  text = text.replace(/\n\n+/g, "\n\n");
  text = text
    .split(/\n\s*\n/)
    .filter((part) => part.trim() !== "")
    .map((part) => `<p>${part.replace(/^\n+|\n+$/g, "").trim()}</p>\n`)
    .join("");
  text = text.replace(/<p>\s*<\/p>/g, "");
  text = text.replace(/<p>([^<]+)<\/(div|address|form)>/gi, "<p>$1</p></$2>");
  text = text.replace(new RegExp(`<p>\\s*(</?${ALL_BLOCKS}[^>]*>)\\s*</p>`, "gi"), "$1");
  text = text.replace(/<p>(<li.+?)<\/p>/gi, "$1");
  text = text.replace(/<p><blockquote([^>]*)>/gi, "<blockquote$1><p>");
  text = text.replace(/<\/blockquote><\/p>/gi, "</p></blockquote>");
  text = text.replace(new RegExp(`<p>\\s*(</?${ALL_BLOCKS}[^>]*>)`, "gi"), "$1");
  text = text.replace(new RegExp(`(</?${ALL_BLOCKS}[^>]*>)\\s*</p>`, "gi"), "$1");
  if (br) {
    text = text.replace(/(?<!<br \/>)\s*\n/g, "<br />\n");
  }
  text = text.replace(new RegExp(`(</?${ALL_BLOCKS}[^>]*>)\\s*<br />`, "gi"), "$1");
  text = text.replace(/<br \/>(\s*<\/?(?:p|li|div|dl|dd|dt|th|pre|td|ul|ol)[^>]*>)/gi, "$1");
  text = text.replace(/\n<\/p>$/g, "</p>");
  text = text.replace(/<pre data-gwp-keep="(\d+)"><\/pre>/g, (_match, index: string) => preserved[Number(index)] ?? "");
  return text;
}

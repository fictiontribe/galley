/**
 * 1-click GitHub Actions scheduled rebuild workflow for static sites using
 * future-dated `publishAt` / `scheduledAt` entries without an always-on server.
 */
import { GalleyError } from "../errors";
import type { SiteService } from "../types";
import type { ScheduleWorkflowResult } from "./types";

export const SCHEDULE_WORKFLOW_PATH = ".github/workflows/galley-schedule.yml";
export const DEFAULT_SCHEDULE_CRON = "0 * * * *";

const CRON_PATTERN = /^[\d*,/-]+\s+[\d*,/-]+\s+[\d*,/-]+\s+[\d*,/-]+\s+[\d*,/-]+$/;

export function renderScheduleWorkflow(options: { cron: string; branch: string; packageManager: string; buildCommand: string }): string {
  const pm = options.packageManager;
  const setupStep =
    pm === "pnpm"
      ? `      - uses: pnpm/action-setup@v4\n      - uses: actions/setup-node@v4\n        with:\n          node-version: 22\n          cache: pnpm\n      - run: pnpm install --frozen-lockfile`
      : pm === "yarn"
        ? `      - uses: actions/setup-node@v4\n        with:\n          node-version: 22\n          cache: yarn\n      - run: yarn install --frozen-lockfile`
        : `      - uses: actions/setup-node@v4\n        with:\n          node-version: 22\n          cache: npm\n      - run: npm ci`;

  return [
    "# Generated by Galley: rebuilds the site on a schedule so future-dated",
    "# entries (publishAt / scheduledAt) go live automatically.",
    "name: Scheduled publish rebuild",
    "",
    "on:",
    "  schedule:",
    `    - cron: ${JSON.stringify(options.cron)}`,
    "  workflow_dispatch:",
    "",
    "permissions:",
    "  contents: read",
    "",
    "jobs:",
    "  rebuild:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "        with:",
    `          ref: ${options.branch}`,
    setupStep,
    `      - run: ${options.buildCommand}`,
    "      # Optional: trigger your static host's deploy hook when configured:",
    "      - name: Trigger deploy hook (if configured)",
    "        if: ${{ secrets.GALLEY_DEPLOY_HOOK_URL != '' }}",
    "        run: curl -fsSL -X POST \"${{ secrets.GALLEY_DEPLOY_HOOK_URL }}\"",
    "",
  ].join("\n");
}

export async function setupScheduleWorkflow(site: SiteService, cronExpression?: string): Promise<ScheduleWorkflowResult> {
  const cron = (cronExpression ?? DEFAULT_SCHEDULE_CRON).trim();

  if (!CRON_PATTERN.test(cron)) {
    throw new GalleyError("invalid", "That cron expression isn't valid (expected 5 fields like “0 * * * *”).");
  }
  const model = await site.model();
  const existing = await site.readFile(SCHEDULE_WORKFLOW_PATH).catch(() => null);
  const content = renderScheduleWorkflow({
    cron,
    branch: model.publish.branch || "main",
    packageManager: model.packageManager ?? "npm",
    buildCommand: model.build?.command ?? "npm run build",
  });

  await site.writeFile(SCHEDULE_WORKFLOW_PATH, content, { origin: "user", mode: "build" });
  return { path: SCHEDULE_WORKFLOW_PATH, cron, created: existing === null };
}

#!/usr/bin/env node
// Minifies src/scripts/runtime.js and src/mailto/runtime.js into their
// runtime.gen.js modules — the text inlined into pages. The package has no build step; this file is
// generated once and committed. `test/scripts.test.ts` fails if it is stale.
//
//   node scripts/build-inline.mjs
//
// @ts-check
// esbuild comes from Astro's own dependencies (a peer of this package), so
// nothing is added to install.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = (/** @type {string} */ path) => fileURLToPath(new URL(path, import.meta.url));

/** The generated modules: source → { file, export name, what it is }. */
export const INLINE = [
  { source: "../src/scripts/runtime.js", out: "../src/scripts/runtime.gen.js", name: "RUNTIME", what: "The scripts runtime as one minified function expression, inlined into <head>." },
  { source: "../src/mailto/runtime.js", out: "../src/mailto/runtime.gen.js", name: "MAILTO_RUNTIME", what: "The email-link dialog as one minified function expression, inlined before </body>." },
];

/** @param {typeof INLINE[number]} [given] */
export async function inlineRuntime(given) {
  const entry = given ?? /** @type {typeof INLINE[number]} */ (INLINE[0]);
  const astro = createRequire(createRequire(import.meta.url).resolve("astro/package.json"));
  const esbuild = astro("esbuild");
  const source = readFileSync(here(entry.source), "utf8");
  const { code } = await esbuild.transform(source, { loader: "js", format: "esm", minify: true, target: "es2018", legalComments: "none" });
  // esbuild writes `function X(o){…}export{X as default};` — keep the function, unnamed.
  const fn = code
    .trim()
    .replace(/export\s*\{\s*\w+ as default\s*\};?$/, "")
    .replace(/^export default /, "")
    .replace(/^function\s*\w*\(/, "function(")
    .trim();

  if (!fn.startsWith("function(")) throw new Error("runtime.js must be one `export default function`.");
  return `// Generated by scripts/build-inline.mjs from runtime.js — do not edit.\n// @ts-check\n/** ${entry.what} */\nexport const ${entry.name} = ${JSON.stringify(fn)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const entry of INLINE) {
    writeFileSync(here(entry.out), await inlineRuntime(entry));
    console.log(`wrote ${entry.out.replace("../", "")}`);
  }
}

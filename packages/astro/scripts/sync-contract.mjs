#!/usr/bin/env node
// Mirrors the site-kit contract from @galley/core into this package, so the
// package can be published (or vendored into a site) with no dependency on
// the Galley workspace:
//
//   packages/core/src/kit.ts          → src/kit.d.ts        (types)
//   packages/core/src/kit-catalog.ts  → src/catalog-data.js (data)
//
// Run it after either core file changes:  node scripts/sync-contract.mjs
// `test/contract.test.ts` fails when the mirrors are stale.
// @ts-check
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (/** @type {string} */ path) => fileURLToPath(new URL(path, import.meta.url));
const CORE = here("../../core/src/");
const OUT = here("../src/");

const NOTE = "Generated by scripts/sync-contract.mjs from packages/core/src/";

/** kit.ts with its one workspace import replaced by the type it imports. */
/** @param {string} source */
export function mirrorKit(source) {
  const json = [
    "/** Any value JSON can hold. (Mirrors JsonValue in @galley/core/types.) */",
    "export type JsonPrimitive = string | number | boolean | null;",
    "export type JsonValue = JsonPrimitive | JsonValue[] | { [key: string]: JsonValue };",
  ].join("\n");
  const body = source.replace(/^import type \{ JsonValue \} from "\.\/types";\n/m, `${json}\n`);

  if (body === source) throw new Error("kit.ts no longer imports JsonValue from ./types; update sync-contract.mjs.");
  return `// ${NOTE}kit.ts — do not edit by hand.\n${body}`;
}

/** kit-catalog.ts with its type annotations removed: plain JavaScript data. */
/** @param {string} source */
export function mirrorCatalog(source) {
  const body = source
    .replace(/^import type [^\n]*\n/m, "")
    .replace(/export const (\w+): \w+\[\] = /g, "export const $1 = ");

  if (/:\s*(FormProviderInfo|ScriptIntegrationInfo)/.test(body)) throw new Error("kit-catalog.ts has annotations sync-contract.mjs does not strip.");
  return `// @ts-check\n// ${NOTE}kit-catalog.ts — do not edit by hand.\n/** @typedef {import("./kit").FormProviderInfo} FormProviderInfo */\n/** @typedef {import("./kit").ScriptIntegrationInfo} ScriptIntegrationInfo */\n${body
    .replace("export const FORM_PROVIDERS = ", "/** @type {FormProviderInfo[]} */\nexport const FORM_PROVIDERS = ")
    .replace("export const SCRIPT_INTEGRATIONS = ", "/** @type {ScriptIntegrationInfo[]} */\nexport const SCRIPT_INTEGRATIONS = ")}`;
}

/** @returns {Record<string, string>} */
export function mirrors() {
  return {
    "kit.d.ts": mirrorKit(readFileSync(`${CORE}kit.ts`, "utf8")),
    "catalog-data.js": mirrorCatalog(readFileSync(`${CORE}kit-catalog.ts`, "utf8")),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [name, text] of Object.entries(mirrors())) {
    writeFileSync(`${OUT}${name}`, text);
    console.log(`wrote src/${name}`);
  }
}

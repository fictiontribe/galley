use std::{env, fs, path::PathBuf};

#[path = "src/brand_source.rs"]
mod brand_source;

/// Every command the shell registers. Listing them here makes tauri-build
/// generate `allow-<command>` permissions and switches the ACL on for app
/// commands, so a window may call only what a capability grants it.
const COMMANDS: &[&str] = &[
    "pick_folder",
    "open_external",
    "reveal_in_finder",
    "startup_state",
    "startup_retry",
    "startup_continue",
    "startup_quit",
];

fn main() {
    write_brand();
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS)),
    )
    .expect("tauri-build failed");
}

/// Generates `brand.rs` from `packages/core/src/brand.ts`, the one place the
/// product is named, and checks the bundle's `productName` agrees with it.
fn write_brand() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let brand_ts = manifest_dir.join("../../../packages/core/src/brand.ts");
    let conf = manifest_dir.join("tauri.conf.json");
    let package_json = manifest_dir.join("../package.json");

    for path in [&brand_ts, &conf, &package_json] {
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let source = fs::read_to_string(&brand_ts)
        .unwrap_or_else(|e| panic!("can't read {}: {e}", brand_ts.display()));
    let brand = brand_source::parse_brand_source(&source)
        .unwrap_or_else(|e| panic!("{}: {e}", brand_ts.display()));
    let conf_json: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&conf).unwrap()).unwrap();
    let product_name = conf_json["productName"].as_str().unwrap_or_default();

    if product_name != brand.name {
        panic!(
            "tauri.conf.json productName is {product_name:?} but packages/core/src/brand.ts names the product {:?}. Make them agree.",
            brand.name
        );
    }

    let package: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&package_json).unwrap()).unwrap();
    let issues_url = package["bugs"]["url"]
        .as_str()
        .expect("apps/desktop/package.json needs bugs.url")
        .to_string();
    let app_version = package["version"].as_str().unwrap_or_default();

    // The app reports its version in About; it must be the engine's.
    if app_version != brand.version {
        panic!("apps/desktop/package.json version is {app_version:?} but packages/core/src/brand.ts VERSION is {:?}. Make them agree.", brand.version);
    }

    let generated = format!(
        "// Generated by build.rs from packages/core/src/brand.ts — do not edit.\n\
         pub const PRODUCT_NAME: &str = {:?};\n\
         pub const TAGLINE: &str = {:?};\n\
         pub const DESCRIPTOR: &str = {:?};\n\
         pub const MAKER: &str = {:?};\n\
         pub const SLUG: &str = {:?};\n\
         pub const DOCS_URL: &str = {:?};\n\
         pub const ISSUES_URL: &str = {:?};\n",
        brand.name,
        brand.tagline,
        brand.descriptor,
        brand.maker,
        brand.slug,
        brand.docs_url,
        issues_url
    );
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("brand.rs");

    fs::write(out, generated).unwrap();
}
